def test_real_preview_files_exist_and_parse(real_manifest: dict) -> None:
    previews_root = ROOT / PREVIEWS_REL
    assert previews_root.is_dir()

    slugs = set()
    preview_paths = set()
    for entry in real_manifest["icons"]:
        slug = entry["slug"]
        preview = entry["preview"]
        assert slug not in slugs
        assert preview not in preview_paths
        slugs.add(slug)
        preview_paths.add(preview)

        path = ROOT / preview
        assert path.is_file(), f"MISSING {preview}"
        text = path.read_text(encoding="utf-8")
        assert "\r" not in text
        assert text.startswith("<!-- Generated by scripts/icons.py from ")
        xml_payload = text.split("\n", 1)[1]
        root_el = ET.fromstring(xml_payload)
        assert root_el.tag == f"{{{SVG_NS}}}svg"

    # no extras on disk
    on_disk = {
        p.relative_to(ROOT).as_posix()
        for p in previews_root.rglob("*.svg")
        if p.is_file()
    }
    assert on_disk == preview_paths


def test_real_preview_paths_posix(real_manifest: dict) -> None:
    for entry in real_manifest["icons"]:
        preview = entry["preview"]
        assert "\\" not in preview
        assert not preview.startswith("/")
        assert preview.startswith("reference/icons/previews/")
