# --- render / safety / well-formedness ----------------------------------------


def test_render_preview_svg_shape() -> None:
    job = PreviewJob(
        rel_path="reference/icons/previews/demo/full-dims.svg",
        slug="demo:full-dims",
        source_json="docs/assets/mermaid-icons/demo.json",
        width=16,
        height=16,
        left=0,
        top=0,
        body='<path d="M0 0h16v16H0z"/>',
    )
    text = render_preview_svg(job)
    assert text.startswith(
        "<!-- Generated by scripts/icons.py from docs/assets/mermaid-icons/demo.json "
        "(demo:full-dims). Do not edit. -->\n"
    )
    assert 'xmlns="http://www.w3.org/2000/svg"' in text
    assert 'xmlns:xlink="http://www.w3.org/1999/xlink"' in text
    assert 'width="16" height="16" viewBox="0 0 16 16"' in text
    assert text.endswith("</svg>\n")
    assert "\r" not in text


def test_script_body_rejected(tmp_path: Path) -> None:
    pack = tmp_path / "docs" / "assets" / "mermaid-icons" / "demo.json"
    _write_pack(
        pack,
        prefix="demo",
        icons={"evil": {"body": '<script>alert(1)</script><path d="M0 0h1v1H0z"/>'}},
    )
    with pytest.raises(IconValidationError) as exc:
        prepare_artifacts(
            root=tmp_path,
            collections=(CollectionSpec("demo", "docs/assets/mermaid-icons/demo.json"),),
        )
    assert any("safety scan" in e for e in exc.value.errors)


