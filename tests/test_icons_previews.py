# --- golden SVGs --------------------------------------------------------------


@pytest.mark.parametrize(
    ("key", "golden_name"),
    [
        ("full-dims", "full-dims.svg"),
        ("collection-default", "collection-default.svg"),
        ("with-offsets", "offsets.svg"),
        ("weird-&-key", "sanitized-filename.svg"),
    ],
)
def test_golden_svgs(tmp_path: Path, key: str, golden_name: str) -> None:
    root, specs = _fixture_root(tmp_path)
    _, jobs = prepare_artifacts(root=root, collections=specs)
    job = next(j for j in jobs if j.slug == f"demo:{key}")
    assert job.rel_path.endswith(filename_for(key))
    rendered = render_preview_svg(job)
    expected = (GOLDEN / golden_name).read_text(encoding="utf-8").replace("\r\n", "\n")
    assert rendered == expected


# --- write / stale cleanup / no-op --------------------------------------------


def test_stale_preview_removed(tmp_path: Path) -> None:
    root, specs = _fixture_root(tmp_path)
    _, jobs = prepare_artifacts(root=root, collections=specs)
    write_previews(jobs, root=root)

    stale = root / PREVIEWS_REL / "demo" / "zzz-not-an-icon.svg"
    stale.write_text("<svg xmlns='http://www.w3.org/2000/svg'/>\n", encoding="utf-8")
    removed = cleanup_stale_previews(jobs, root=root)
    assert not stale.exists()
    assert any(r.endswith("zzz-not-an-icon.svg") for r in removed)


def test_unchanged_preview_not_rewritten(tmp_path: Path) -> None:
    root, specs = _fixture_root(tmp_path)
    _, jobs = prepare_artifacts(root=root, collections=specs)
    written1, unchanged1 = write_previews(jobs, root=root)
    assert written1 == len(jobs) and unchanged1 == 0

    path = root / jobs[0].rel_path
    mtime_before = path.stat().st_mtime_ns
    time.sleep(0.02)
    written2, unchanged2 = write_previews(jobs, root=root)
    assert written2 == 0 and unchanged2 == len(jobs)
    assert path.stat().st_mtime_ns == mtime_before


def test_write_if_changed_skips_identical(tmp_path: Path) -> None:
    path = tmp_path / "a.svg"
    assert write_if_changed(path, "hello\n") is True
    assert write_if_changed(path, "hello\n") is False
    assert write_if_changed(path, "hello\r\n") is False  # normalised compare
    assert write_if_changed(path, "other\n") is True


